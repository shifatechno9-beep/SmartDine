export type Locale = "ar" | "fr" | "en";

export const LOCALES: {
  code: Locale;
  short: string;
  label: string;
}[] = [
  { code: "ar", short: "AR", label: "العربية" },
  { code: "fr", short: "FR", label: "Français" },
  { code: "en", short: "EN", label: "English" },
];

export const DEFAULT_LOCALE: Locale = "fr";
export const LOCALE_COOKIE = "smartdine-locale";

export function isLocale(value: string | undefined | null): value is Locale {
  return value === "ar" || value === "fr" || value === "en";
}

export function parseLocale(value: string | undefined | null): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

export function localeDir(locale: Locale): "rtl" | "ltr" {
  return locale === "ar" ? "rtl" : "ltr";
}

export function formatMad(amount: number, locale: Locale) {
  const safe = Number.isFinite(amount) ? amount : 0;
  const formatted = new Intl.NumberFormat(
    locale === "ar" ? "ar-MA" : locale === "fr" ? "fr-MA" : "en-MA",
    {
      maximumFractionDigits: 2,
      minimumFractionDigits: Number.isInteger(safe) ? 0 : 2,
    },
  ).format(safe);

  return locale === "ar" ? `${formatted} د.م.` : `${formatted} MAD`;
}

